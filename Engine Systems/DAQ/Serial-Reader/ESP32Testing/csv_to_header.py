# csv_to_header.py - turn a pressure CSV into test_data.h for esp32-synnax-oled and
# esp32-synnax-led
#
# The ESP32 has no file system the Arduino IDE can upload to without a plugin, so the
# test rows are compiled into the firmware instead. Each sketch gets its own copy, since
# the IDE only sees files in the sketch's folder. Run this, then re-flash:
#
#   python3 csv_to_header.py "oled_test.ino/Coldflow Raw Data - Test 2.csv"
#
# The CSV needs a header row naming five pressure columns. "pressure1", "pressure_1"
# and "Pressure 1" all match. Rows above the header (notes, event logs) and rows that
# don't parse as numbers are skipped. Other columns are ignored.

import csv
import math
import re
import sys
from pathlib import Path

OUT_PATHS = [Path(__file__).parent / sketch / "test_data.h"
             for sketch in ("esp32-synnax-oled", "esp32-synnax-led")]
WANTED = [f"pressure{i}" for i in range(1, 6)]


def normalize(name):
    return re.sub(r"[\s_]", "", name).lower()


def read_rows(csv_path):
    columns = None
    rows = []
    skipped = 0
    with open(csv_path, newline="", encoding="utf-8-sig") as f:
        for record in csv.reader(f):
            if columns is None:
                names = [normalize(n) for n in record]
                if all(w in names for w in WANTED):
                    columns = [names.index(w) for w in WANTED]
                continue
            try:
                values = [float(record[i]) for i in columns]
            except (IndexError, ValueError):
                skipped += 1
                continue
            if not all(math.isfinite(v) for v in values):
                skipped += 1
                continue
            rows.append(values)
    if columns is None:
        sys.exit(f"No header row with columns {', '.join(WANTED)} in {csv_path}")
    if not rows:
        sys.exit(f"No numeric pressure rows under the header in {csv_path}")
    return rows, skipped


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: python3 csv_to_header.py <pressure csv>")
    csv_path = Path(sys.argv[1])
    rows, skipped = read_rows(csv_path)

    lines = [
        f"// Generated by csv_to_header.py from \"{csv_path.name}\" - do not edit by hand.",
        f"// {len(rows)} rows of pressure_1..pressure_5. The firmware replays them in order",
        "// and starts again from the first row at the end.",
        "#pragma once", 
        "",
        f"const char TEST_DATA_SOURCE[] = \"{csv_path.name}\";",
        f"const int TEST_ROW_COUNT = {len(rows)};",
        "const float TEST_ROWS[][5] = {",
    ] #prettu sure the #pragma once line is straight black magic???
    lines += ["  {" + ", ".join(f"{v!r}f" for v in row) + "}," for row in rows]
    lines += ["};", ""]
    for out_path in OUT_PATHS:
        out_path.write_text("\n".join(lines))
        print(f"Wrote {len(rows)} rows to {out_path}")
    if skipped:
        print(f"Skipped {skipped} rows under the header that weren't five numbers")


if __name__ == "__main__":
    main()
